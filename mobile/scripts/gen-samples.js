// Generates src/lib/samples.ts from docs/samples/*.txt (the "Load sample" helper).
// The UI title comes from the dictionaries, keyed by id (the file name without .txt).
// Run: node scripts/gen-samples.js
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', '..', 'docs', 'samples');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.txt')).sort();
const titles = {
  '00-indonesia-he.txt': 'Singapore & Indonesia, 21 days (Hebrew)',
  '01-israel-he.txt': 'Israel, 8 days (Hebrew)',
  '02-japan-chatgpt-en.txt': 'Japan, ChatGPT-style',
  '03-italy-table-en.txt': 'Italy, table format',
  '04-messy-notes-en.txt': 'Messy notes',
  '05-mixed-he-en.txt': 'Greece, mixed Hebrew/English',
  '06-no-times-en.txt': 'Portugal, no times',
};
const items = files.map((f) => ({
  id: f.replace(/\.txt$/, ''),
  title: titles[f] ?? f,
  text: fs.readFileSync(path.join(dir, f), 'utf8').trim(),
}));
const out =
  '// GENERATED by scripts/gen-samples.js from docs/samples/*.txt. Do not edit by hand.\n\n' +
  'export type Sample = { id: string; title: string; text: string };\n\n' +
  'export const SAMPLES: Sample[] = ' + JSON.stringify(items, null, 2) + ';\n';
fs.mkdirSync(path.join(__dirname, '..', 'src', 'lib'), { recursive: true });
fs.writeFileSync(path.join(__dirname, '..', 'src', 'lib', 'samples.ts'), out);
console.log('wrote', items.length, 'samples');
